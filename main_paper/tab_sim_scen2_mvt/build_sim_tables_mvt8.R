############################################################
# Build Scenario 1/2 MVT8 (df=8) joint-vs-separate LaTeX tables.
# Writes two labels from one run: tab:sim_scen1_mvt, tab:sim_scen2_mvt
# Args: [ROOT] [OUT_TEX]
#   ROOT    = HPC results folder containing
#             s1_n200_mvt8/ s1_n400_mvt8/ s2_n200_mvt8/ s2_n400_mvt8/
#   OUT_TEX = output .tex path
############################################################
args <- commandArgs(trailingOnly = TRUE)

script_dir <- local({
  f <- grep("^--file=", commandArgs(trailingOnly = FALSE), value = TRUE)
  if (length(f)) {
    dirname(normalizePath(sub("^--file=", "", f[[1]]), winslash = "/", mustWork = FALSE))
  } else {
    getwd()
  }
})
repo_root <- normalizePath(file.path(script_dir, "..", ".."), winslash = "/", mustWork = FALSE)

ROOT <- if (length(args) >= 1L) args[[1]] else {
  file.path(repo_root, "hpc_jobs", "mvt8_sc12_n200n400_s500_taiyuan_20260915")
}
OUT_TEX <- if (length(args) >= 2L) args[[2]] else {
  file.path(repo_root, "sim_tables_mvt8.tex")
}

# Shared formatting helpers live next to this script or in 00_shared/.
helper_path <- local({
  cand <- c(
    file.path(script_dir, "build_sim_tables.R"),
    file.path(repo_root, "00_shared", "build_sim_tables.R")
  )
  hit <- cand[file.exists(cand)]
  if (!length(hit)) stop("build_sim_tables.R not found next to this script or in 00_shared/")
  hit[[1]]
})
helper <- readLines(helper_path, encoding = "UTF-8", warn = FALSE)
cut_at <- grep("^has_dir <- function", helper)[1]
if (!is.finite(cut_at)) stop("Cannot locate helpers in build_sim_tables.R")
ROOT_KEEP <- ROOT
OUT_TEX_KEEP <- OUT_TEX
eval(parse(text = paste(helper[seq_len(cut_at - 1L)], collapse = "\n")))
ROOT <- ROOT_KEEP
OUT_TEX <- OUT_TEX_KEEP

s1_a <- load_setting(file.path(ROOT, "s1_n200_mvt8"))
s1_b <- load_setting(file.path(ROOT, "s1_n400_mvt8"))
s2_a <- load_setting(file.path(ROOT, "s2_n200_mvt8"))
s2_b <- load_setting(file.path(ROOT, "s2_n400_mvt8"))

tex <- c(
  "% Auto-generated by build_sim_tables_mvt8.R - do not edit by hand",
  "% Taiyuan MVT8 (df=8) Sc1/Sc2, N_SIM=500, chain 10000/5000/5, G=8.",
  make_table(list(s1_a, s1_b), c(200L, 400L), 1L, "tab:sim_scen1_mvt", "mvt"),
  make_table(list(s2_a, s2_b), c(200L, 400L), 2L, "tab:sim_scen2_mvt", "mvt")
)
dir.create(dirname(OUT_TEX), recursive = TRUE, showWarnings = FALSE)
writeLines(tex, OUT_TEX, useBytes = TRUE)
cat("Wrote", OUT_TEX, "\n")
cat("S1 N200 joint AL alpha1:", s1_a$joint$AL[s1_a$joint$Parameter == "alpha1"][1], "\n")
cat("S2 N200 mean CP:", mean(s2_a$joint$CP[!grepl("^delta", s2_a$joint$Parameter)], na.rm = TRUE), "\n")
