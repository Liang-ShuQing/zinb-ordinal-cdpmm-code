############################################################
# Build Scenario 3 LaTeX tables (portrait, N stacked; same layout as Sc1/2).
# Writes three labels from one run:
#   tab:sim_scen3_normal, tab:sim_scen3, tab:sim_scen3_mvt
# Args: [ROOT] [OUT_TEX]
#   ROOT    = HPC results folder containing
#             s3_n200_normal/ s3_n400_normal/ s3_n200_mixture/ s3_n400_mixture/
#             s3_n200_mvt8/   s3_n400_mvt8/
#   OUT_TEX = output .tex path
############################################################
args <- commandArgs(trailingOnly = TRUE)

script_dir <- local({
  f <- grep("^--file=", commandArgs(trailingOnly = FALSE), value = TRUE)
  if (length(f)) {
    dirname(normalizePath(sub("^--file=", "", f[[1]]), winslash = "/", mustWork = FALSE))
  } else {
    getwd()
  }
})
repo_root <- normalizePath(file.path(script_dir, "..", ".."), winslash = "/", mustWork = FALSE)

ROOT <- if (length(args) >= 1L) args[[1]] else {
  file.path(repo_root, "hpc_jobs", "scen3v2_mvt8_n200n400_s500_wuzhen_20260915")
}
OUT_TEX <- if (length(args) >= 2L) args[[2]] else {
  file.path(repo_root, "sim_tables_scen3.tex")
}

# Shared formatting helpers live next to this script or in 00_shared/.
helper_path <- local({
  cand <- c(
    file.path(script_dir, "build_sim_tables.R"),
    file.path(repo_root, "00_shared", "build_sim_tables.R")
  )
  hit <- cand[file.exists(cand)]
  if (!length(hit)) stop("build_sim_tables.R not found next to this script or in 00_shared/")
  hit[[1]]
})
helper <- readLines(helper_path, encoding = "UTF-8", warn = FALSE)
cut_at <- grep("^has_dir <- function", helper)[1]
if (!is.finite(cut_at)) stop("Cannot locate helpers in build_sim_tables.R")
ROOT_KEEP <- ROOT
OUT_TEX_KEEP <- OUT_TEX
eval(parse(text = paste(helper[seq_len(cut_at - 1L)], collapse = "\n")))
ROOT <- ROOT_KEEP
OUT_TEX <- OUT_TEX_KEEP

s3_n200_n <- load_setting(file.path(ROOT, "s3_n200_normal"))
s3_n400_n <- load_setting(file.path(ROOT, "s3_n400_normal"))
s3_n200_m <- load_setting(file.path(ROOT, "s3_n200_mixture"))
s3_n400_m <- load_setting(file.path(ROOT, "s3_n400_mixture"))
s3_n200_t <- load_setting(file.path(ROOT, "s3_n200_mvt8"))
s3_n400_t <- load_setting(file.path(ROOT, "s3_n400_mvt8"))

tex <- c(
  "% Auto-generated by build_sim_tables_scen3.R - do not edit by hand",
  "% Scenario 3v2 portrait (Wuzhen, no-interact 4/3/5): N_SIM=500, chain 10000/5000/5, G=8.",
  "% --- Normal random-effects truth ---",
  make_table(list(s3_n200_n, s3_n400_n), c(200L, 400L), 3L, "tab:sim_scen3_normal", "normal"),
  "% --- Mixture random-effects truth ---",
  make_table(list(s3_n200_m, s3_n400_m), c(200L, 400L), 3L, "tab:sim_scen3", "mixture"),
  "% --- Multivariate-t (df=8) random-effects truth ---",
  make_table(list(s3_n200_t, s3_n400_t), c(200L, 400L), 3L, "tab:sim_scen3_mvt", "mvt")
)
dir.create(dirname(OUT_TEX), recursive = TRUE, showWarnings = FALSE)
writeLines(tex, OUT_TEX, useBytes = TRUE)
cat("Wrote", OUT_TEX, "\n")
cat("Normal N200 joint AL alpha1:", s3_n200_n$joint$AL[s3_n200_n$joint$Parameter == "alpha1"][1], "\n")
cat("Mixture N200 mean CP:", mean(s3_n200_m$joint$CP[!grepl("^delta", s3_n200_m$joint$Parameter)], na.rm = TRUE), "\n")
cat("MVT8 N200 mean CP:", mean(s3_n200_t$joint$CP[!grepl("^delta", s3_n200_t$joint$Parameter)], na.rm = TRUE), "\n")
