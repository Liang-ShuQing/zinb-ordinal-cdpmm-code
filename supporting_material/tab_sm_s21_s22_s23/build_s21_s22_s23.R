emit_lr <- function(d2, d4) {
  stopifnot(identical(d2$Parameter, d4$Parameter))
  paste0(
    d2$Label, " & ", fmt_true(d2$True_Value), " & ",
    fmt_num(d2$Bias), " & ", fmt_num(d2$RMSE), " & ", fmt_num(d2$CP), " & ",
    fmt_num(d4$Bias), " & ", fmt_num(d4$RMSE), " & ", fmt_num(d4$CP), " \\\\"
  )
}

