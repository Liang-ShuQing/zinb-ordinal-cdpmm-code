    "\\textbf{Parameter} & \\textbf{True Value} & \\multicolumn{3}{c}{\\textbf{$N=200$}} & \\multicolumn{3}{c}{\\textbf{$N=400$}} \\\\\n",
    "\\cmidrule(lr){3-5}\\cmidrule(lr){6-8}\n",
