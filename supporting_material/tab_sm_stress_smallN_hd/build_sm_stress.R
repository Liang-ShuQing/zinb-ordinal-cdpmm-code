fmt_num <- function(x) {
  s <- sprintf("%.3f", x)
  ifelse(x < 0, paste0("$", s, "$"), s)
}
fmt_true <- function(x) {
  is_int <- abs(x - round(x)) < 1e-9
  s <- ifelse(is_int & abs(x) >= 2, sprintf("%g", x),
       ifelse(is_int, sprintf("%.1f", x),
              format(round(x, 3), scientific = FALSE, trim = TRUE)))
  s <- ifelse(x < 0, paste0("$", s, "$"), s)
  s
}

read_rows <- function(csv, name_map) {
  d <- read.csv(csv, stringsAsFactors = FALSE)
  out <- d[d$Parameter %in% names(name_map), ]
  out$Label <- name_map[out$Parameter]
  out[order(match(out$Parameter, names(name_map))), ]
}

emit_block <- function(d) {
  paste0(
    d$Label, " & ", fmt_true(d$True_Value), " & ",
    fmt_num(d$Bias), " & ", fmt_num(d$RMSE), " & ", fmt_num(d$CP), " \\\\"
  )
}

table_wrap <- function(body, caption, label) {
  paste0(
    "%% AUTO-GENERATED by build_sm_stress.R -- do not edit by hand\n",
    "\\begin{table}[htbp]\n\\centering\n",
    "\\caption{", caption, "}\n",
    "\\label{", label, "}\n",
    "\\begin{adjustbox}{max width=\\textwidth,center}\n\\scriptsize\n",
    "\\setlength{\\tabcolsep}{3pt}\n",
    "\\begin{tabular}{lcccc}\n\\toprule\n",
    "\\textbf{Parameter} & \\textbf{True Value} & Bias & RMSE & CP \\\\\n",
    "\\midrule\n", body, "\n\\bottomrule\n\\end{tabular}\n",
    "\\end{adjustbox}\n\\end{table}\n"
  )
}

